// Regenerates src/data/timezones.ts, src/data/utcOffsets.ts, and
// src/data/standardOffsets.ts from this machine's ICU/tzdata. Run manually via
// `npm run generate:timezones` and review the diff — this is NOT run automatically
// as part of `build`/CI (see README/plan for why).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Some ICU/tzdata builds report legacy link names as "canonical" even though IANA's
// tzdata has since renamed the primary identifier (see tzdata's `backward` file).
// Both spellings are valid Intl inputs; prefer the modern spelling for the public API.
// Re-verify this table whenever re-running the script on a different ICU version.
const LEGACY_TO_MODERN = {
  'Asia/Calcutta': 'Asia/Kolkata',
  'Asia/Katmandu': 'Asia/Kathmandu',
  'Asia/Rangoon': 'Asia/Yangon',
  'Asia/Saigon': 'Asia/Ho_Chi_Minh',
  'America/Godthab': 'America/Nuuk',
  'Europe/Kiev': 'Europe/Kyiv',
};

function getTimeZoneOffsetMinutes(timeZone, date) {
  const dtf = new Intl.DateTimeFormat('en-US', {
    timeZone,
    hourCycle: 'h23',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });
  const parts = {};
  for (const part of dtf.formatToParts(date)) {
    if (part.type !== 'literal') parts[part.type] = part.value;
  }
  const hour = parts.hour === '24' ? '00' : parts.hour;
  const asUTC = Date.UTC(
    Number(parts.year),
    Number(parts.month) - 1,
    Number(parts.day),
    Number(hour),
    Number(parts.minute),
    Number(parts.second),
  );
  return Math.round((asUTC - date.getTime()) / 60_000);
}

// `Intl.supportedValuesOf('timeZone')` omits the whole `Etc/*` namespace on this
// ICU build, including plain `'UTC'` — even though `'UTC'` is a specially-recognized,
// always-valid Intl timeZone identifier and the single most commonly expected zone
// for consumers to be able to enable. Add it explicitly if missing.
const rawZones = Intl.supportedValuesOf('timeZone');
const zoneSet = new Set(rawZones.map((tz) => LEGACY_TO_MODERN[tz] ?? tz));
zoneSet.add('UTC');
const zones = Array.from(zoneSet).sort();

// Sample across a year (one date per month) per zone. DST always moves the clock
// forward relative to standard time (i.e. increases the numeric UTC offset), so a
// zone's standard (non-DST) offset is always the *minimum* of its samples — this
// holds regardless of hemisphere, without needing to know each zone's actual DST
// transition dates.
const referenceYear = new Date().getUTCFullYear();
const sampleDates = Array.from(
  { length: 12 },
  (_, month) => new Date(Date.UTC(referenceYear, month, 15, 12, 0, 0)),
);

const standardOffsetByZone = {};
for (const zone of zones) {
  let standardOffset = Infinity;
  for (const date of sampleDates) {
    standardOffset = Math.min(standardOffset, getTimeZoneOffsetMinutes(zone, date));
  }
  standardOffsetByZone[zone] = standardOffset;
}

// The canonical line grid is the set of distinct *standard* offsets in use — a
// DST-only offset (e.g. a zone's summer time) isn't drawn as its own line, since
// zones are bucketed by standard offset regardless of the current date.
const offsets = Array.from(new Set(Object.values(standardOffsetByZone))).sort((a, b) => a - b);

const timezonesFile = new URL('../src/data/timezones.ts', import.meta.url);
writeFileSync(
  timezonesFile,
  `// AUTO-GENERATED by scripts/generate-timezones.mjs — do not hand-edit.\n` +
    `// Regenerate with \`npm run generate:timezones\` and review the diff.\n\n` +
    `export const IANA_TIME_ZONES = [\n${zones.map((z) => `  '${z}',`).join('\n')}\n] as const;\n`,
);

const offsetsFile = new URL('../src/data/utcOffsets.ts', import.meta.url);
writeFileSync(
  offsetsFile,
  `// AUTO-GENERATED by scripts/generate-timezones.mjs — do not hand-edit.\n` +
    `// Regenerate with \`npm run generate:timezones\` and review the diff.\n` +
    `// Every distinct standard (non-DST) UTC offset (in minutes) across all IANA zones.\n\n` +
    `export const UTC_OFFSET_MINUTES = [\n${offsets.map((m) => `  ${m},`).join('\n')}\n] as const;\n`,
);

const standardOffsetsFile = new URL('../src/data/standardOffsets.ts', import.meta.url);
writeFileSync(
  standardOffsetsFile,
  `// AUTO-GENERATED by scripts/generate-timezones.mjs — do not hand-edit.\n` +
    `// Regenerate with \`npm run generate:timezones\` and review the diff.\n` +
    `// Each zone's standard (non-DST) UTC offset in minutes — used to bucket zones onto\n` +
    `// the map's fixed-longitude lines independent of the current date/DST, so a zone's\n` +
    `// line always matches its true geographic position.\n\n` +
    `export const STANDARD_OFFSET_MINUTES: Record<string, number> = {\n${zones
      .map((z) => `  '${z}': ${standardOffsetByZone[z]},`)
      .join('\n')}\n};\n`,
);

console.log(`Wrote ${zones.length} time zones to ${fileURLToPath(timezonesFile)}`);
console.log(`Wrote ${offsets.length} canonical UTC offsets to ${fileURLToPath(offsetsFile)}`);
console.log(`Wrote ${zones.length} standard offsets to ${fileURLToPath(standardOffsetsFile)}`);
